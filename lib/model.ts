// The token radar's model, radar-2: one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and ranks
// every other pre-token protocol that passes the same product rule: a protocol is a launch candidate
// only when it is not a wrapped, staked or bridged product of a token that already trades. That rule
// is the watchlist's own, applied to the whole board: WBTC is Bitcoin on Ethereum, Binance staked
// ETH is ETH in a staking product, a bridge moves somebody else's token, and an exchange is not a
// protocol waiting on a launch. Those protocols are not hidden: they are set aside with their reason
// and shown in the dashboard's Set aside view, next to the live-token protocols whose market cap is
// a fact, not a model.
//
// Implied value follows only from the snapshot's own figures:
//
//   base       = tvl_usd x BASE_MULTIPLE
//   growth     = clamp(change_7d, -50, 150) per cent
//   growthMult = 1 + (growth / 100) x GROWTH_WEIGHT
//   maturity   = 0.55 + min(age_days, 1460) / 1460 x 0.45   (age_days unknown: 365)
//   breadth    = 1 + min(chains - 1, 6) x 0.02             (one chain: 1.00, seven or more: 1.12)
//   implied    = max(1, round(base x growthMult x maturity x breadth))
//   (the floor of 1 keeps a protocol with no TVL on the board, ranked at the bottom, not dropped)
//
// TVL is the size of the prize, seven-day growth is its direction, age with no token is how long the
// launch has been waited for, and chain breadth is how widely the protocol is already distributed.
// The constants are the radar-2 model's, stated in the dashboard and changeable in its sandbox. No
// protocol name is ever special-cased: the same function scores every row.

